#include <stdio.h>

int main() {

    int a = 25, b = 7;
    int Penjumlahan = a + b;
    int Pengurangan = a - b;
    int Perkalian = a * b;
    int Pembagian = a / b;
    int Sisa = a % b;

    printf("Hasil Penjumlahan   = %d\n", Penjumlahan);
    printf("Hasil Pengurangan   = %d\n", Pengurangan);
    printf("Hasil Perkalian     = %d\n", Perkalian);
    printf("Hasil Pembagian     = %d\n", Pembagian);
    printf("Hasil Sisa          = %d\n", Sisa);

    return 0;
}