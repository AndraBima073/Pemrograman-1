#include <stdio.h>

int main(void) {
    float c, f, r, k;

    printf("========================================================\n");
    printf("|  Celsius  | Fahrenheit |   Reamur   |    Kelvin    |\n");
    printf("========================================================\n");

    for (c = 0; c <= 100; c += 10) {

        f = (c * 9.0 / 5.0) + 32.0;
        r = c * 4.0 / 5.0;
        k = c + 273.15;

        printf("| %9.2f | %10.2f | %10.2f | %12.2f |\n", c, f, r, k);
    }
    
    printf("========================================================\n");
    return 0;
}